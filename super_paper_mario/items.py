class ItemConfigOverride(TypedDict, total=False):
    count: int
    clazz: IC


CONFIG_OVERRIDES: dict[str, tuple[Callable[[SuperPaperMarioOptions], bool], ItemConfigOverride]] = {
    "h": (lambda options: options.shuffle_pure_hearts.value, {"count": 1}),
    "f": (lambda options: options.trading_quest.value, {"count": 1}),
    # "ck": (lambda options: options.chapter_door_access == ChapterDoorAccess.option_chapters_closed, {"count": 1}),
    # "sk": (lambda options: options.chapter_door_access == ChapterDoorAccess.option_subchapters_closed, {"count": 1}),
    "a": (lambda options: options.ability_shuffle.value, {"count": 1}),
    "m": (lambda options: options.treasure_maps.map_items_in_pool, {"count": 1}),
}


def prepare_item_data(world: SPMWorldBase) -> list[ItemSetup]:
    # Construct a dictionary of tag to count/classification to override ItemData defaults
    overrides: dict[str, ItemConfigOverride] = {
        tag: override for tag, (func, override) in CONFIG_OVERRIDES.items() if func(world.options)
    }

    # Apply the overrides from the base item data
    return [
        (item_data, replace(item_config, **overrides[item_data.tag]))
        if item_data.tag and overrides.get(item_data.tag, None) is not None
        else (item_data, item_config)
        for item_data, item_config in ITEM_SETUP
    ]


def create_items(world: SPMWorldBase, item_setup: list[ItemSetup]) -> list[SPMItem]:
    return [
        create_item(world, (data, config)) if data.name in ItemName else world.create_event()
        for (data, config) in item_setup
        for _ in range(0, config.count or 0)
    ]


def create_item(world: SPMWorldBase, data: ItemSetup) -> SPMItem:
    return SPMItem(data[0].name, data[1].clazz or IC.filler, data[0].code, world.player)


